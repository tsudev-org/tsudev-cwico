#!/usr/bin/env bash
# Nộp manifest winget của một phiên bản lên microsoft/winget-pkgs (RELEASING.md mục 7).
#
#   scripts/submit-winget.sh 26.11.1002
#
# Không clone kho winget-pkgs (rất lớn): tạo fork nếu chưa có, tạo nhánh từ đầu
# master của upstream, đẩy mọi tệp manifest của phiên bản qua API, rồi mở pull request.
# Cần `gh` đã đăng nhập bằng tài khoản sẽ đứng tên PR. Sau khi PR mở, ký CLA
# của Microsoft nếu bot yêu cầu.
set -euo pipefail

VERSION="${1:?cần phiên bản semver, ví dụ 26.11.1002}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="manifests/t/tsudev/cwico/$VERSION"
SRC="$ROOT/packaging/winget/$DIR"
[ -d "$SRC" ] || { echo "không có $SRC - chạy tools/apply_winget_manifest.py trước" >&2; exit 1; }

ME="$(gh api user --jq .login)"
BRANCH="tsudev.cwico-$VERSION"
UP="microsoft/winget-pkgs"

if ! gh repo view "$ME/winget-pkgs" >/dev/null 2>&1; then
  gh repo fork "$UP" --clone=false --default-branch-only
  for _ in $(seq 1 30); do gh repo view "$ME/winget-pkgs" >/dev/null 2>&1 && break; sleep 5; done
fi

BASE="$(gh api "repos/$UP/git/ref/heads/master" --jq .object.sha)"
# Fork vừa tạo hoặc cũ: đồng bộ để có commit BASE.
gh api -X POST "repos/$ME/winget-pkgs/merge-upstream" -f branch=master >/dev/null 2>&1 || true
gh api -X POST "repos/$ME/winget-pkgs/git/refs" -f ref="refs/heads/$BRANCH" -f sha="$BASE" >/dev/null

for f in "$SRC"/*.yaml; do
  name="$(basename "$f")"
  gh api -X PUT "repos/$ME/winget-pkgs/contents/$DIR/$name" \
    -f message="New version: tsudev.cwico version $VERSION" \
    -f branch="$BRANCH" \
    -f content="$(base64 -w0 "$f")" >/dev/null
  echo "đã đẩy $DIR/$name"
done

gh pr create -R "$UP" --head "$ME:$BRANCH" --base master \
  --title "New version: tsudev.cwico version $VERSION" \
  --body "Release: https://github.com/tsudev-org/tsudev-cwico/releases/tag/$(python3 "$ROOT/tools/version.py" to-name "$VERSION")

Manifests generated by the project's release workflow and checked against the published installer (URL + SHA256)."
